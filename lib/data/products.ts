export function isCategory(value: string): value is Category {
  return (categories as string[]).includes(value);
}

export function getCategoryInfo(value: string): CategoryInfo | undefined {
  return isCategory(value) ? categoryInfo[value] : undefined;
}

export function getProductsByCategory(category: Category): Product[] {
  return products.filter((product) => product.category === category);
}

export function getProduct(category: string, id: number): Product | undefined {
  return products.find((product) => product.category === category && product.id === id);
}

export function productHref(product: Pick<Product, "category" | "id">): string {
  return `/products/${product.category}/${product.id}`;
}

export function searchProducts(query: string): Product[] {
  const term = query.trim().toLowerCase();
  if (!term) return [];
  return products
    .filter((product) => {
      const haystack = `${product.name} ${product.description} ${categoryInfo[product.category].label}`.toLowerCase();
      return haystack.includes(term);
    })
    .slice(0, 12);
}
